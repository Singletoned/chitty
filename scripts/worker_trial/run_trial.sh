#!/bin/sh
# Run one `chitty run` work session on one ticket in a throwaway clone.
# See docs/plan/worker-trials.md for the method and what went wrong before.
#
# Usage: run_trial.sh <variant> <ticket> <base> [<ticket-branch-start>]
#   variant  one of the names in the `case` below
#   ticket   e.g. TASK-512
#   base     commit the clone's main is reset to; for a done ticket use
#            `find_base.sh <ticket>`, so later work cannot leak in
#   ticket-branch-start  optional commit to start the ticket's branch from,
#            for a ticket whose latest text is on a branch; omit to start fresh
# Environment:
#   TRIAL_DIR      required: this round's folder, e.g. tmp/worker-trial/round2
#   TRIAL_TIMEOUT  seconds before the run is killed (default 7200)
#
# The clone has no remote, so nothing can be pushed back, and a project name of
# its own, so it never takes over the real project's registry entry or inbox.
# Do not edit this file while trials are running: `sh` reads a script as it
# runs, so running copies pick up shifted text.
set -eu

[ $# -ge 3 ] || { sed -n '4,15p' "$0" >&2; exit 2; }
variant=$1
ticket=$2
base=$3
start=${4:-}
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
: "${TRIAL_DIR:?set TRIAL_DIR to this round\'s folder, e.g. tmp/worker-trial/round2}"
mkdir -p "$TRIAL_DIR"
trial_dir=$(cd "$TRIAL_DIR" && pwd)
pi_root=$repo/tmp/worker-trial/pi
branch=$(printf '%s' "$ticket" | tr 'A-Z' 'a-z')
dir=$trial_dir/runs/$variant--$branch
round=$(basename "$trial_dir")  # in the project name, so rounds never share an inbox

run='env -u VIRTUAL_ENV -u UV_PROJECT_ENVIRONMENT uv run --no-sync'
pi_args='-p --no-extensions --no-skills --skill ~/.pi/agent/skills/python-dev'
claude_args="--permission-mode bypassPermissions --disallowedTools 'Bash(git push *)'"
lean=no
case $variant in
    pi152-luna) agent="$run $pi_root/1.5.2/node_modules/.bin/pi $pi_args --model openai-codex/gpt-6-luna {prompt}" ;;
    pi152-terra) agent="$run $pi_root/1.5.2/node_modules/.bin/pi $pi_args --model openai-codex/gpt-6.1-terra {prompt}" ;;
    pi160-luna) agent="$run $pi_root/1.6.0/node_modules/.bin/pi $pi_args --model openai-codex/gpt-6-luna {prompt}" ;;
    pi160-terra) agent="$run $pi_root/1.6.0/node_modules/.bin/pi $pi_args --model openai-codex/gpt-6.1-terra {prompt}" ;;
    pi152-luna-lean)
        agent="$run $pi_root/1.5.2/node_modules/.bin/pi $pi_args --model openai-codex/gpt-6-luna {prompt}"
        lean=yes ;;
    codex-luna) agent="$run $here/codex_agent.sh --model gpt-6-luna {prompt}" ;;
    codex-terra) agent="$run $here/codex_agent.sh --model gpt-6.1-terra {prompt}" ;;
    claude-haiku) agent="$run claude -p {prompt} --model haiku $claude_args" ;;
    claude-sonnet) agent="$run claude -p {prompt} --model sonnet $claude_args" ;;
    # `agy -c` continues the machine's most recent conversation, so run at most
    # one agy trial at a time.
    agy) agent="$run agy -p {prompt} --dangerously-skip-permissions --model gemini-3.8-flash-medium" ;;
    agy-hydrogen) agent="$run agy -p {prompt} --dangerously-skip-permissions --model gemini-4-hydrogen-medium" ;;
    *) echo "unknown variant: $variant" >&2; exit 2 ;;
esac
case $variant in pi*)
    pi=${agent#"$run "}; pi=${pi%% *}
    [ -x "$pi" ] || { echo "$pi is missing; run scripts/worker_trial/setup.sh" >&2; exit 1; } ;;
esac

rm -rf "$dir" "$dir".*.out
mkdir -p "$trial_dir/runs"
git clone --quiet --no-hardlinks "$repo" "$dir"
cd "$dir"
# A clone starts on the source checkout's branch, which need not be main.
git checkout --quiet -B main "$base"
if [ -n "$start" ]; then
    git branch --quiet "$branch" "$start"
fi
git remote remove origin

sed -i '' "s/^project = \"chitty\"/project = \"chitty-trial-$round-$variant-$branch\"/" chitty.toml
[ "$(grep '^\[' chitty.toml | tail -1)" = '[agent_commands]' ] || {
    echo "the base's chitty.toml does not end with [agent_commands]" >&2; exit 1; }
printf 'trial = "%s"\n' "$agent" >> chitty.toml

if [ $lean = yes ]; then
    cp "$here/lean-work.md" src/chitty/roles/work.md
    python3 - <<'EOF'
from pathlib import Path

path = Path("src/chitty/run.py")
text = path.read_text()
start = text.index('            f"Continue working only on Chitty ticket {ticket_id}.')
end = text.index('        )\n    return (\n        f"Continue reviewing')
text = text[:start] + (
    '            f"Continue implementing Chitty ticket {ticket_id}. Keep going until it is "\n'
    '            "finished and set to `review`. Do not stop with it unfinished."\n'
) + text[end:]
path.write_text(text)
test = Path("tests/test_run_continue.py")
test.write_text(
    test.read_text().replace(
        '"Continue working only on Chitty ticket "', '"Continue implementing Chitty ticket "'
    )
)
EOF
fi
git add -A
git commit --quiet -m "Trial setup: $variant"

# The runner builds prompts from its own code, so use the clone's install.
make install > "$dir.install.out" 2>&1
chitty=$dir/.venv/bin/chitty

if git show-ref --quiet "refs/heads/$branch"; then
    git worktree add --quiet ".worktrees/$branch" "$branch"
    (cd ".worktrees/$branch" && "$chitty" edit "$ticket" -s todo --owner '' --note "Trial reset to todo." >/dev/null)
else
    "$chitty" edit "$ticket" -s todo --owner '' --note "Trial reset to todo." >/dev/null
fi

started=$(date +%s)
set +e
timeout "${TRIAL_TIMEOUT:-7200}" "$chitty" run --ticket "$ticket" --agent trial > "$dir.run.out" 2>&1
code=$?
set -e
seconds=$(($(date +%s) - started))

worktree=$dir/.worktrees/$branch
status=$(cd "$worktree" 2>/dev/null && "$chitty" show "$ticket" | sed -n 's/^status: //p' || echo unknown)
commits=$(git rev-list --count "main..$branch" 2>/dev/null || echo 0)
(cd "$worktree" 2>/dev/null && "$chitty" show "$ticket" --json) > "$dir.ticket.json" || true
results=$trial_dir/results.tsv
[ -s "$results" ] || printf 'variant\tticket\tbase\texit\tstatus\tseconds\tbranch_commits\n' > "$results"
printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$variant" "$ticket" "$(git rev-parse --short "$base")" \
    "$code" "$status" "$seconds" "$commits" | tee -a "$results"
